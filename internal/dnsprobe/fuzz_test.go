package dnsprobe

import "testing"

// The answer of a name server is read from the network.
func FuzzParseSOA(f *testing.F) {
	f.Add([]byte("\x12\x34\x81\x80\x00\x01\x00\x01\x00\x00\x00\x00\x07example\x03com\x00\x00\x06\x00\x01\xc0\x0c\x00\x06\x00\x01\x00\x00\x0e\x10\x00\x16\x02ns\xc0\x0c\x02hm\xc0\x0c\x78\x5a\x00\x01\x00\x00\x0e\x10\x00\x00\x07\x08\x00\x09\x3a\x80\x00\x00\x0e\x10"))
	f.Add([]byte("\x00\x00\x81\x80\x00\x01\x00\x01\x00\x00\x00\x00\xc0\x0c"))
	f.Fuzz(func(t *testing.T, m []byte) {
		if len(m) < 12 {
			return // the reader checks this
		}
		_, _, _ = parseSOA(m)
	})
}
